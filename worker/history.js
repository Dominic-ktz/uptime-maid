import { readFileSync, writeFileSync, existsSync, renameSync } from 'node:fs';

export function emptyHistory() {
  return { services: {}, incidents: [], lastUpdated: null };
}

export function loadHistory(path) {
  if (!existsSync(path)) return emptyHistory();
  try {
    const data = JSON.parse(readFileSync(path, 'utf-8'));
    return {
      services: data.services ?? {},
      incidents: (data.incidents ?? []).map(migrateIncident),
      lastUpdated: data.lastUpdated ?? null,
    };
  } catch (err) {
    // Nicht stillschweigend überschreiben: lieber abbrechen, als 90 Tage History zu verlieren.
    throw new Error(`History-Datei ${path} ist beschädigt: ${err.message}`);
  }
}

/** Ältere Auto-Incidents (v1) hatten nur `timestamp` + `newStatus`. */
function migrateIncident(inc) {
  if (inc.startedAt || inc.autoGenerated !== true) return inc;
  return {
    id: inc.id,
    serviceId: inc.serviceId,
    serviceName: inc.serviceName,
    title: inc.title,
    status: inc.newStatus === 'online' ? 'resolved' : inc.newStatus,
    startedAt: inc.timestamp,
    resolvedAt: inc.newStatus === 'online' ? inc.timestamp : null,
    autoGenerated: true,
  };
}

/**
 * Trägt ein Check-Ergebnis ein und pflegt automatische Vorfälle.
 * Gibt den Statuswechsel zurück (oder null), damit der Aufrufer benachrichtigen kann.
 */
export function recordCheck(history, service, result, now) {
  const entry = (history.services[service.id] ??= { checks: [] });
  const prevStatus = entry.checks.at(-1)?.status ?? null;

  const check = { timestamp: now, status: result.status, responseTime: result.responseTime };
  if (result.details && Object.keys(result.details).length) check.details = result.details;
  entry.checks.push(check);

  const changed = prevStatus !== result.status && !(prevStatus === null && result.status === 'online');
  if (!changed) return null;

  updateIncidents(history, service, prevStatus, result, now);
  return { from: prevStatus, to: result.status };
}

function updateIncidents(history, service, prevStatus, result, now) {
  const open = history.incidents.find((i) => i.autoGenerated && i.serviceId === service.id && !i.resolvedAt);

  if (result.status === 'online') {
    if (open) {
      open.status = 'resolved';
      open.resolvedAt = now;
      open.title = `${service.name}: Störung behoben`;
    }
    return;
  }

  const title = result.status === 'offline'
    ? `${service.name} ist nicht erreichbar`
    : `${service.name} ist beeinträchtigt`;

  if (open) {
    open.status = result.status;
    open.title = title;
    if (result.details?.error) open.error = result.details.error;
    return;
  }

  history.incidents.push({
    id: `auto-${service.id}-${Date.parse(now)}`,
    serviceId: service.id,
    serviceName: service.name,
    title,
    status: result.status,
    startedAt: now,
    resolvedAt: null,
    ...(result.details?.error ? { error: result.details.error } : {}),
    autoGenerated: true,
  });
}

/**
 * Entfernt alte Checks, Vorfälle und Services, die weder konfiguriert sind noch Daten haben.
 * Offene Vorfälle bleiben immer erhalten.
 */
export function pruneHistory(history, maxDays, configuredIds, now = new Date()) {
  const cutoff = new Date(now.getTime() - maxDays * 86_400_000).toISOString();
  const configured = new Set(configuredIds);

  for (const [id, svc] of Object.entries(history.services)) {
    svc.checks = (svc.checks ?? []).filter((c) => c.timestamp >= cutoff);
    if (!svc.checks.length && !configured.has(id)) delete history.services[id];
  }

  history.incidents = history.incidents.filter(
    (i) => !i.resolvedAt || i.resolvedAt >= cutoff
  );
}

/**
 * Schreibt die History mit einem Check pro Zeile: deutlich kleiner als komplett eingerückt
 * und trotzdem lesbare Git-Diffs.
 */
export function serializeHistory(history) {
  const services = Object.entries(history.services).map(([id, svc]) => {
    const checks = svc.checks.length
      ? `[\n${svc.checks.map((c) => `        ${JSON.stringify(c)}`).join(',\n')}\n      ]`
      : '[]';
    return `    ${JSON.stringify(id)}: {\n      "checks": ${checks}\n    }`;
  });

  const incidents = JSON.stringify(history.incidents, null, 2).replace(/\n/g, '\n  ');

  return [
    '{',
    `  "lastUpdated": ${JSON.stringify(history.lastUpdated)},`,
    `  "services": {${services.length ? `\n${services.join(',\n')}\n  ` : ''}},`,
    `  "incidents": ${incidents}`,
    '}',
    '',
  ].join('\n');
}

/** Atomar schreiben, damit ein abgebrochener Lauf keine halbe JSON-Datei hinterlässt. */
export function writeFileAtomic(path, content) {
  const tmp = `${path}.tmp`;
  writeFileSync(tmp, content, 'utf-8');
  renameSync(tmp, path);
}
